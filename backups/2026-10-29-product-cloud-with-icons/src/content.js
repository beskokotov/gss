export function makeMailto({ name = '', contact = '', message = '', topic = 'Демонстрация системы ГАРАНТ' }) {
  const body = `Здравствуйте!\n\nТема: ${topic}\nИмя: ${name.trim()}\nКонтакт для ответа: ${contact.trim()}\n\n${message.trim()}`;
  return `mailto:${contacts.email}?subject=${encodeURIComponent(topic)}&body=${encodeURIComponent(body)}`;
}
